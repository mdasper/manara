'use client';
import React, { useEffect, useState } from 'react';
import { getAIAlerts } from '@/lib/api';
import { Link } from 'react-router-dom';

export default function NotificationsPage() {
    const [alerts, setAlerts] = useState([]);
    const [loading, setLoading] = useState(true);
    const [activeTab, setActiveTab] = useState('all');
    const [dismissed, setDismissed] = useState([]);

    useEffect(() => {
        loadAlerts();
    }, []);

    const loadAlerts = async () => {
        try {
            setLoading(true);
            const res = await getAIAlerts();
            setAlerts(res.data);
        }
        catch (err) {
            console.error('Error fetching alerts:', err);
        }
        finally {
            setLoading(false);
        }
    };

    const handleDismiss = (entityId) => {
        setDismissed(prev => [...prev, entityId]);
    };

    const visibleAlerts = alerts
        .filter(a => !dismissed.includes(a.entity_id))
        .filter(a => {
            if (activeTab === 'high')
                return a.severity === 'high';
            if (activeTab === 'medium')
                return a.severity === 'medium';
            if (activeTab === 'lease')
                return a.type.includes('lease');
            if (activeTab === 'rent')
                return a.type.includes('rent') || a.type.includes('payment');
            if (activeTab === 'maintenance')
                return a.type.includes('maintenance');
            return true;
        });

    const getAlertIcon = (type) => {
        if (type.includes('lease'))
            return '📋';
        if (type.includes('rent') || type.includes('payment'))
            return '💰';
        if (type.includes('maintenance'))
            return '🔧';
        return '🔔';
    };

    const getAlertDestination = (type) => {
        if (type.includes('lease'))
            return '/leases';
        if (type.includes('rent') || type.includes('payment'))
            return '/payments';
        if (type.includes('maintenance'))
            return '/maintenance';
        return '/dashboard';
    };

    return (
      <div className="page-container animate-fade-in">
        <div className="page-header animate-in">
          <div className="flex items-center justify-between">
            <div>
              <h1 className="page-title">Notification Center</h1>
              <p className="page-subtitle">
                Automated alerts generated by SmartProperty AI rules engine for urgent dates and events.
              </p>
            </div>
            <button
              onClick={() => setDismissed(alerts.map(a => a.entity_id))}
              className="btn btn-secondary btn-sm"
            >
              Clear All
            </button>
          </div>
        </div>

        {/* Tabs with horizontal touch scroll */}
        <div className="notifications-filter-bar animate-in">
          {[
              { id: 'all', label: `All Alerts (${alerts.length - dismissed.length})` },
              { id: 'high', label: 'High Priority 🚨' },
              { id: 'lease', label: 'Lease Expiries 📋' },
              { id: 'rent', label: 'Rent Dues 💰' },
              { id: 'maintenance', label: 'Maintenance 🔧' },
          ].map(tab => (
            <button
              key={tab.id}
              onClick={() => setActiveTab(tab.id)}
              className={`notifications-tab-pill ${activeTab === tab.id ? 'active' : ''}`}
            >
              {tab.label}
            </button>
          ))}
        </div>

        {loading ? (
          <div style={{ textAlign: 'center', padding: '3rem', color: 'var(--text-muted)' }}>
            Checking notifications...
          </div>
        ) : visibleAlerts.length === 0 ? (
          <div className="card" style={{ textAlign: 'center', padding: '4rem 1rem' }}>
            <div style={{ fontSize: '3rem', marginBottom: '0.75rem' }}>🎉</div>
            <h3 style={{ margin: '0 0 0.5rem 0', color: 'var(--text-primary)' }}>All caught up!</h3>
            <p style={{ color: 'var(--text-secondary)', margin: 0, fontSize: '0.875rem' }}>
              No pending or urgent alerts require your attention right now.
            </p>
          </div>
        ) : (
          <div className="notifications-list">
            {visibleAlerts.map(alert => {
              const isHigh = alert.severity === 'high';
              return (
                <div
                  key={alert.entity_id + alert.type}
                  className={`notification-card ${isHigh ? 'severity-high' : 'severity-med'}`}
                >
                  {/* Top Bar: Icon + Badge + Dismiss */}
                  <div className="notif-header">
                    <div className="notif-header-left">
                      <div className={`notif-icon-box ${isHigh ? 'icon-high' : 'icon-med'}`}>
                        {getAlertIcon(alert.type)}
                      </div>
                      <span className={`notif-badge ${isHigh ? 'badge-high' : 'badge-med'}`}>
                        {alert.severity}
                      </span>
                    </div>
                    <button
                      onClick={() => handleDismiss(alert.entity_id)}
                      className="notif-dismiss-btn"
                      title="Dismiss"
                    >
                      ✕
                    </button>
                  </div>

                  {/* Body: Title & Message */}
                  <div className="notif-body">
                    <h4 className="notif-title">
                      {alert.title}
                    </h4>
                    <p className="notif-message">
                      {alert.message}
                    </p>
                  </div>

                  {/* Footer: Action Button */}
                  <div className="notif-footer">
                    <Link to={getAlertDestination(alert.type)} className="notif-action-link">
                      <button className="btn btn-primary notif-action-btn">
                        Take Action &rarr;
                      </button>
                    </Link>
                  </div>
                </div>
              );
            })}
          </div>
        )}
      </div>
    );
}
